"""Writes EscalopWiFi/certs.h: the root certificates the Wi-Fi module trusts for HTTPS.

Usage: python make_certs.py cacert.pem
cacert.pem is Mozilla's CA list as published by curl: https://curl.se/ca/cacert.pem
"""
import os
import re
import sys

# github.com / api.github.com use Sectigo (USERTrust); release downloads and escaloplab.com use Let's Encrypt (ISRG).
# The others are there so a routine change of certificate authority doesn't stop updates.
ROOTS = [
    "ISRG Root X1",
    "ISRG Root X2",
    "USERTrust RSA Certification Authority",
    "USERTrust ECC Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
]


def main():
    bundle = open(sys.argv[1], encoding="utf-8").read()
    lines = [
        "#pragma once",
        "",
        "// Root certificates the Wi-Fi module trusts for HTTPS, from Mozilla's CA list (https://curl.se/ca/cacert.pem).",
        "// Generated by tools/escaloplab/esp01/make_certs.py; don't edit by hand.",
        "",
        'static const char TRUST_ANCHORS[] PROGMEM = R"PEM(',
    ]
    for name in ROOTS:
        m = re.search(r"^" + re.escape(name) + r"\n=+\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)",
                      bundle, re.S | re.M)
        if not m:
            sys.exit("not in the bundle: " + name)
        lines += [m.group(1)]
    lines += [')PEM";', ""]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "EscalopWiFi", "certs.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
