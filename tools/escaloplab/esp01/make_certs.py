"""Writes EscalopWiFi/certs.h: the root certificates the Wi-Fi module trusts for HTTPS.

Usage: python make_certs.py cacert.pem
cacert.pem is Mozilla's CA list as published by curl: https://curl.se/ca/cacert.pem
"""
import os
import re
import sys

# One root per site family, and only these two: every root costs RAM while connecting, and the ESP-01 has only
# ~35 KB free for HTTPS (a connection loads just the root its host needs). If GitHub or Let's Encrypt change their
# root, regenerate this file and ship a module update (the web page's manual update needs no HTTPS).
ROOTS = [
    ("ROOT_GITHUB", "USERTrust ECC Certification Authority"),  # github.com, api.github.com (via Sectigo E46)
    ("ROOT_LETSENCRYPT", "ISRG Root X1"),                       # release downloads, escaloplab.com
]


def main():
    bundle = open(sys.argv[1], encoding="utf-8").read()
    lines = [
        "#pragma once",
        "",
        "// Root certificates the Wi-Fi module trusts for HTTPS, from Mozilla's CA list (https://curl.se/ca/cacert.pem).",
        "// Generated by tools/escaloplab/esp01/make_certs.py; don't edit by hand.",
        "",
    ]
    for const, name in ROOTS:
        m = re.search(r"^" + re.escape(name) + r"\n=+\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)",
                      bundle, re.S | re.M)
        if not m:
            sys.exit("not in the bundle: " + name)
        lines += ["// " + name, "static const char " + const + '[] PROGMEM = R"PEM(', m.group(1), ')PEM";', ""]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "EscalopWiFi", "certs.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
